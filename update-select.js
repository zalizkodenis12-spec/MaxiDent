const lines = rawData.split('\n').filter(l => l.trim());
let optionsHtml = '\n              <option value="" disabled selected>Оберіть послугу...</option>\n';

let currentCategory = '';

for (const line of lines) {
  if (!line.includes('\t') && !line.includes('грн') && !line.match(/\d/)) {
    // It's a category
    if (currentCategory) {
      optionsHtml += '              </optgroup>\n';
    }
    currentCategory = line.trim();
    optionsHtml += `              <optgroup label="${currentCategory}">\n`;
  } else {
    // It's a service
    const parts = line.split('\t');
    let name = parts[0].trim();
    let price = parts[1] ? parts[1].trim() : '';
    // if not split by tab, try split by double space or something?
    if (!price) {
        // try to extract price from end
        const match = name.match(/(.*?)\s+((?:від\s+)?\d[\d\s-]*грн?)/);
        if (match) {
            name = match[1].trim();
            price = match[2].trim();
        }
    }
    
    // We only put the name in the value, but show name + price in the text.
    let displayText = name;
    if (price) {
        if (!price.includes('грн')) price += ' грн';
        displayText += ` (${price})`;
    }
    
    optionsHtml += `                <option value="${name}">${displayText}</option>\n`;
  }
}
if (currentCategory) {
  optionsHtml += '              </optgroup>\n';
}

const htmlFile = 'd:/Мої сайти/MaksiDent_site/index.html';
let htmlContent = fs.readFileSync(htmlFile, 'utf8');

const regex = /<select id="f-service" name="service" [^>]+>([\s\S]*?)<\/select>/;
const match = htmlContent.match(regex);

if (match) {
  htmlContent = htmlContent.replace(match[1], optionsHtml + '            ');
  fs.writeFileSync(htmlFile, htmlContent, 'utf8');
  console.log('Successfully updated index.html with all services.');
} else {
  console.log('Could not find select element in index.html');
}
